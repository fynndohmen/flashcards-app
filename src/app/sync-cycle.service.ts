// src/app/sync-cycle.service.ts

import { Injectable } from '@angular/core';

import { IncrementalPushReport, IncrementalPushService } from './incremental-push.service';

import { IncrementalPullReport, IncrementalSyncService } from './incremental-sync.service';

import { ImageSyncSnapshot, StoredSyncMeta } from './sync-metadata.models';

import { SyncStorageService } from './sync-storage.service';

export interface SyncCycleEntityCounts {
  decks: number;
  cards: number;
  images: number;
  total: number;
}

export interface SyncCycleReport {
  startedAt: string;

  completedAt: string;

  initialPull: IncrementalPullReport;

  push: IncrementalPushReport;

  finalPull: IncrementalPullReport;

  serverRevisionBefore: number;

  serverRevisionAfter: number;

  pushedAnything: boolean;

  changedAnything: boolean;

  lastSuccessfulSyncAt: string;

  autoResolvedImageConflicts: number;

  unresolvedConflicts: SyncCycleEntityCounts;

  pendingOperations: SyncCycleEntityCounts;
}

@Injectable({
  providedIn: 'root',
})
export class SyncCycleService {
  private activeCycle: Promise<SyncCycleReport> | null = null;

  constructor(
    private incrementalPull: IncrementalSyncService,
    private incrementalPush: IncrementalPushService,
    private syncStorage: SyncStorageService,
  ) {}

  /**
   * Complete normal synchronization cycle:
   *
   *   1. Pull remote changes
   *   2. Apply them / create conflicts
   *   3. Push independent local pending changes
   *   4. Pull again to consume revisions created by our push
   *   5. Auto-resolve converged image-position changes
   *   6. Record lastSuccessfulSyncAt
   *
   * Existing conflicts do not block unrelated entities.
   */
  async syncOnce(): Promise<SyncCycleReport> {
    /*
     * Coalesce duplicate sync requests.
     *
     * Multiple callers wait for the same cycle instead of
     * starting concurrent network operations.
     */
    if (this.activeCycle) {
      return this.activeCycle;
    }

    const task = this.runSyncCycle();

    this.activeCycle = task;

    try {
      return await task;
    } finally {
      this.activeCycle = null;
    }
  }

  async syncOnceAndLog(): Promise<SyncCycleReport> {
    const report = await this.syncOnce();

    console.group('Flashcards complete sync cycle');

    console.log('SYNC COMPLETE — pull → push → pull finished.');

    console.log({
      startedAt: report.startedAt,

      completedAt: report.completedAt,

      serverRevisionBefore: report.serverRevisionBefore,

      serverRevisionAfter: report.serverRevisionAfter,

      pushedAnything: report.pushedAnything,

      changedAnything: report.changedAnything,

      lastSuccessfulSyncAt: report.lastSuccessfulSyncAt,

      autoResolvedImageConflicts: report.autoResolvedImageConflicts,

      unresolvedConflicts: report.unresolvedConflicts,

      pendingOperations: report.pendingOperations,
    });

    console.log('Initial pull', report.initialPull);

    console.log('Push', report.push);

    console.log('Final pull', report.finalPull);

    console.groupEnd();

    return report;
  }

  private async runSyncCycle(): Promise<SyncCycleReport> {
    const startedAt = new Date().toISOString();

    /*
     * Phase 1:
     *
     * Consume everything the server already knows about.
     * This can convert stale local mutations into conflicts
     * before we attempt to push them.
     */
    const initialPull = await this.incrementalPull.pullAndApply();

    /*
     * Phase 2:
     *
     * Push all remaining non-conflicting local changes.
     *
     * The push service deliberately does not advance the
     * global pull cursor.
     */
    const push = await this.incrementalPush.pushPending();

    /*
     * Phase 3:
     *
     * Consume revisions generated by our own pushes, plus
     * anything another client may have written meanwhile.
     */
    const finalPull = await this.incrementalPull.pullAndApply();

    const completedAt = new Date().toISOString();

    let autoResolvedImageConflicts = 0;

    /*
     * Image deletion has one special property:
     *
     * Local image arrays compact immediately when an image
     * is removed:
     *
     *   [A, B] -> [B]
     *
     * Therefore B changes locally from position 1 to 0.
     *
     * The server performs the same compaction after accepting
     * the delete and bumps B's revision because its position
     * changed.
     *
     * During the final pull the generic conflict detector may
     * therefore temporarily observe:
     *
     *   base:   position 1
     *   local:  position 0
     *   server: position 0
     *
     * This is not a real conflict: local and server have
     * independently converged to the exact same image
     * metadata.
     *
     * Only clean image records are auto-resolved here.
     * Pending image creates/deletes are never silently
     * resolved by this rule.
     */
    const finalMeta = await this.syncStorage.updateSyncMeta((meta) => {
      if (!meta.initialized) {
        throw new Error('Sync metadata became uninitialized during a completed sync cycle.');
      }

      autoResolvedImageConflicts = this.autoResolveConvergedImageConflicts(meta);

      meta.lastSuccessfulSyncAt = completedAt;
    });

    const unresolvedConflicts = this.countConflicts(finalMeta);

    const pendingOperations = this.countPendingOperations(finalMeta);

    const changedAnything =
      initialPull.changedLocalState ||
      initialPull.changedSyncMetadata ||
      push.pushedAnything ||
      push.counts.conflictsCreated > 0 ||
      finalPull.changedLocalState ||
      finalPull.changedSyncMetadata ||
      autoResolvedImageConflicts > 0;

    return {
      startedAt,

      completedAt,

      initialPull,

      push,

      finalPull,

      serverRevisionBefore: initialPull.serverRevisionBefore,

      serverRevisionAfter: finalMeta.serverRevision,

      pushedAnything: push.pushedAnything,

      changedAnything,

      lastSuccessfulSyncAt: completedAt,

      autoResolvedImageConflicts,

      unresolvedConflicts,

      pendingOperations,
    };
  }

  private autoResolveConvergedImageConflicts(meta: StoredSyncMeta): number {
    let resolved = 0;

    for (const record of Object.values(meta.images)) {
      const conflict = record.conflict;

      if (!conflict) {
        continue;
      }

      /*
       * Never auto-resolve a local mutation that is still
       * waiting to be pushed.
       */
      if (record.pendingOperation !== null) {
        continue;
      }

      /*
       * Delete-vs-active and active-vs-delete situations
       * remain real conflicts and require an explicit user
       * decision.
       */
      if (conflict.localDeleted || conflict.serverDeleted) {
        continue;
      }

      if (!conflict.local || !conflict.server) {
        continue;
      }

      const local = conflict.local as ImageSyncSnapshot;

      const server = conflict.server as ImageSyncSnapshot;

      if (!this.imageSnapshotsEqual(local, server)) {
        continue;
      }

      /*
       * Both sides independently reached exactly the same
       * active image metadata.
       *
       * Accept the newer server revision as the new clean
       * ancestor.
       */
      record.revision = conflict.serverRevision;

      record.baseRevision = conflict.serverRevision;

      record.pendingOperation = null;

      record.lastSyncedSnapshot = this.clone(server);

      record.conflict = null;

      resolved += 1;
    }

    return resolved;
  }

  private imageSnapshotsEqual(a: ImageSyncSnapshot, b: ImageSyncSnapshot): boolean {
    return a.id === b.id && a.cardId === b.cardId && a.side === b.side && a.position === b.position;
  }

  private countConflicts(meta: StoredSyncMeta): SyncCycleEntityCounts {
    const decks = Object.values(meta.decks).filter((record) => record.conflict !== null).length;

    const cards = Object.values(meta.cards).filter((record) => record.conflict !== null).length;

    const images = Object.values(meta.images).filter((record) => record.conflict !== null).length;

    return {
      decks,
      cards,
      images,

      total: decks + cards + images,
    };
  }

  private countPendingOperations(meta: StoredSyncMeta): SyncCycleEntityCounts {
    const decks = Object.values(meta.decks).filter(
      (record) => record.pendingOperation !== null,
    ).length;

    const cards = Object.values(meta.cards).filter(
      (record) => record.pendingOperation !== null,
    ).length;

    const images = Object.values(meta.images).filter(
      (record) => record.pendingOperation !== null,
    ).length;

    return {
      decks,
      cards,
      images,

      total: decks + cards + images,
    };
  }

  private clone<T>(value: T): T {
    try {
      return structuredClone(value);
    } catch {
      return JSON.parse(JSON.stringify(value)) as T;
    }
  }
}
