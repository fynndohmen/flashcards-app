// src/app/sync-cycle.service.ts

import { Injectable } from '@angular/core';

import { IncrementalPushReport, IncrementalPushService } from './incremental-push.service';

import { IncrementalPullReport, IncrementalSyncService } from './incremental-sync.service';

import { StoredSyncMeta } from './sync-metadata.models';

import { SyncStorageService } from './sync-storage.service';

export interface SyncCycleEntityCounts {
  decks: number;
  cards: number;
  images: number;
  total: number;
}

export interface SyncCycleReport {
  startedAt: string;

  completedAt: string;

  initialPull: IncrementalPullReport;

  push: IncrementalPushReport;

  finalPull: IncrementalPullReport;

  serverRevisionBefore: number;

  serverRevisionAfter: number;

  pushedAnything: boolean;

  changedAnything: boolean;

  lastSuccessfulSyncAt: string;

  unresolvedConflicts: SyncCycleEntityCounts;

  pendingOperations: SyncCycleEntityCounts;
}

@Injectable({
  providedIn: 'root',
})
export class SyncCycleService {
  private activeCycle: Promise<SyncCycleReport> | null = null;

  constructor(
    private incrementalPull: IncrementalSyncService,
    private incrementalPush: IncrementalPushService,
    private syncStorage: SyncStorageService,
  ) {}

  async syncOnce(): Promise<SyncCycleReport> {
    /*
     * Coalesce duplicate sync requests.
     *
     * If the user starts sync twice, both callers wait for
     * the same cycle instead of running concurrent network
     * operations.
     */
    if (this.activeCycle) {
      return this.activeCycle;
    }

    const task = this.runSyncCycle();

    this.activeCycle = task;

    try {
      return await task;
    } finally {
      this.activeCycle = null;
    }
  }

  async syncOnceAndLog(): Promise<SyncCycleReport> {
    const report = await this.syncOnce();

    console.group('Flashcards complete sync cycle');

    console.log('SYNC COMPLETE — pull → push → pull finished.');

    console.log({
      startedAt: report.startedAt,

      completedAt: report.completedAt,

      serverRevisionBefore: report.serverRevisionBefore,

      serverRevisionAfter: report.serverRevisionAfter,

      pushedAnything: report.pushedAnything,

      changedAnything: report.changedAnything,

      lastSuccessfulSyncAt: report.lastSuccessfulSyncAt,

      unresolvedConflicts: report.unresolvedConflicts,

      pendingOperations: report.pendingOperations,
    });

    console.log('Initial pull', report.initialPull);

    console.log('Push', report.push);

    console.log('Final pull', report.finalPull);

    console.groupEnd();

    return report;
  }

  private async runSyncCycle(): Promise<SyncCycleReport> {
    const startedAt = new Date().toISOString();

    /*
     * Phase 1:
     *
     * First consume remote changes. This detects conflicts
     * before stale local mutations are allowed to push.
     */
    const initialPull = await this.incrementalPull.pullAndApply();

    /*
     * Phase 2:
     *
     * Push every remaining non-conflicting local mutation.
     */
    const push = await this.incrementalPush.pushPending();

    /*
     * Phase 3:
     *
     * Consume revisions generated by our own pushes and any
     * other server changes that appeared in the meantime.
     */
    const finalPull = await this.incrementalPull.pullAndApply();

    const completedAt = new Date().toISOString();

    /*
     * Only a completely successful pull → push → pull cycle
     * updates lastSuccessfulSyncAt.
     */
    const finalMeta = await this.syncStorage.updateSyncMeta((meta) => {
      if (!meta.initialized) {
        throw new Error('Sync metadata became uninitialized during a completed sync cycle.');
      }

      meta.lastSuccessfulSyncAt = completedAt;
    });

    const unresolvedConflicts = this.countConflicts(finalMeta);

    const pendingOperations = this.countPendingOperations(finalMeta);

    const changedAnything =
      initialPull.changedLocalState ||
      initialPull.changedSyncMetadata ||
      push.pushedAnything ||
      push.counts.conflictsCreated > 0 ||
      finalPull.changedLocalState ||
      finalPull.changedSyncMetadata;

    return {
      startedAt,

      completedAt,

      initialPull,

      push,

      finalPull,

      serverRevisionBefore: initialPull.serverRevisionBefore,

      serverRevisionAfter: finalMeta.serverRevision,

      pushedAnything: push.pushedAnything,

      changedAnything,

      lastSuccessfulSyncAt: completedAt,

      unresolvedConflicts,

      pendingOperations,
    };
  }

  private countConflicts(meta: StoredSyncMeta): SyncCycleEntityCounts {
    const decks = Object.values(meta.decks).filter((record) => record.conflict !== null).length;

    const cards = Object.values(meta.cards).filter((record) => record.conflict !== null).length;

    const images = Object.values(meta.images).filter((record) => record.conflict !== null).length;

    return {
      decks,
      cards,
      images,

      total: decks + cards + images,
    };
  }

  private countPendingOperations(meta: StoredSyncMeta): SyncCycleEntityCounts {
    const decks = Object.values(meta.decks).filter(
      (record) => record.pendingOperation !== null,
    ).length;

    const cards = Object.values(meta.cards).filter(
      (record) => record.pendingOperation !== null,
    ).length;

    const images = Object.values(meta.images).filter(
      (record) => record.pendingOperation !== null,
    ).length;

    return {
      decks,
      cards,
      images,

      total: decks + cards + images,
    };
  }
}
